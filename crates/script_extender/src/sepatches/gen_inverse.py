"""Writes inverse_unrolled.rs: the engine's 4x4 inverse (FUN_1413778b0) as straight-line Rust.

Run:  python gen_inverse.py > inverse_unrolled.rs

Same floating-point operations in the same order as the engine's loops (see `det3` and
`inverse_rows` in ../sepatches.rs, which stay in the crate as the reference the tests compare
against). Nothing is simplified algebraically: the constant row (0,0,0,1) keeps its multiplies
and adds, because `0.0 * x` and `x + 0.0` are not identities for NaN / inf / -0.0.
"""

# full 4x4 as names f0..f15 (row-major); f12..f14 = 0.0, f15 = 1.0 are the literals below
FULL = [f"f{i}" for i in range(16)]
LIT = {"f12": "0.0f32", "f13": "0.0f32", "f14": "0.0f32", "f15": "1.0f32"}


def v(i):
    n = FULL[i]
    return LIT.get(n, n)


def det3_call(minor):
    return "d3(" + ", ".join(v(i) for i in minor) + ")"


out = []
w = out.append
w("// @generated by gen_inverse.py - do not edit")
w("/// Straight-line form of `inverse_rows` (same operations, same order).")
w("#[inline(always)]")
w("pub fn inverse_rows_unrolled(m: &[f32; 12]) -> [f32; 12] {")
for i in range(12):
    w(f"    let f{i} = m[{i}];")
w("    let mut det = 0.0f32;")
for i in range(4):
    lead = v(i * 4)
    if i & 1:
        lead = f"-{lead}"
    rows = [r for r in range(4) if r != i]
    minor = [r * 4 + c for r in rows for c in (1, 2, 3)]
    w(f"    det += {lead} * {det3_call(minor)};")
w("    if !(det.abs() >= f32::MIN_POSITIVE) {")
w("        return *m;")
w("    }")
w("    let inv = 1.0f32 / det;")
w("    [")
for i in range(3):
    row = []
    for j in range(4):
        rows = [r for r in range(4) if r != j]
        minor = [r * 4 + c for r in rows for c in range(4) if c != i]
        sign = "-1.0f32" if (i + j) & 1 else "1.0f32"
        row.append(f"({det3_call(minor)} * {sign}) * inv")
    w("        " + ", ".join(row) + ",")
w("    ]")
w("}")
print("\n".join(out))
